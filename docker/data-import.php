<?php

// One-off import: copies the rows of a SQLite file into the app's default
// database connection (MariaDB). The target schema must already exist,
// i.e. `php artisan migrate` must have run before this script.
//
// Usage: php docker/data-import.php /path/to/database.sqlite

$sqlitePath = $argv[1] ?? null;

if ($sqlitePath === null || ! is_file($sqlitePath)) {
    fwrite(STDERR, "Usage: php docker/data-import.php <path-to-sqlite-file>\n");
    exit(1);
}

require __DIR__.'/../vendor/autoload.php';

$app = require __DIR__.'/../bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();

// Runtime tables are regenerated by the app itself and must not be copied,
// migrations is rewritten by `php artisan migrate` on the target.
$skip = [
    'migrations',
    'cache',
    'cache_locks',
    'sessions',
    'jobs',
    'job_batches',
    'failed_jobs',
    'password_reset_tokens',
];

$pdo = new PDO('sqlite:'.$sqlitePath, null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);

$mariadb = DB::connection()->getPdo();
$mariadb->exec("SET SESSION sql_mode = 'NO_BACKSLASH_ESCAPES'");
$mariadb->exec('SET FOREIGN_KEY_CHECKS=0');

$tables = $pdo->query(
    "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
)->fetchAll(PDO::FETCH_COLUMN);

$columnsStatement = $mariadb->prepare(
    'SELECT COLUMN_NAME FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ?'
);

$totalRows = 0;
$importedTables = 0;

foreach ($tables as $table) {
    if (in_array($table, $skip, true)) {
        fwrite(STDOUT, sprintf("skipped:            %-25s (runtime table)\n", $table));

        continue;
    }

    $columnsStatement->execute([$table]);
    $targetColumns = $columnsStatement->fetchAll(PDO::FETCH_COLUMN);

    if ($targetColumns === []) {
        fwrite(STDOUT, sprintf("skipped:            %-25s (no target table)\n", $table));

        continue;
    }

    $sqliteColumns = [];
    foreach ($pdo->query('PRAGMA table_info(`'.$table.'`)') as $column) {
        $sqliteColumns[$column['name']] = strtoupper($column['type']);
    }

    // Copy only columns that exist on both sides, in the target's order.
    $common = array_values(array_filter(
        $targetColumns,
        static fn (string $name): bool => array_key_exists($name, $sqliteColumns),
    ));

    $selects = array_map(
        static fn (string $name): string => $sqliteColumns[$name] === 'BLOB'
            ? 'quote(CAST(`'.$name.'` AS BLOB))'
            : 'quote(`'.$name.'`)',
        $common,
    );

    $rows = $pdo->query('SELECT '.implode(', ', $selects).' FROM `'.$table.'`')
        ->fetchAll(PDO::FETCH_NUM);

    $mariadb->exec('TRUNCATE TABLE `'.$table.'`');

    $columnList = implode(', ', array_map(
        static fn (string $name): string => '`'.$name.'`',
        $common,
    ));

    foreach ($rows as $row) {
        $mariadb->exec('INSERT INTO `'.$table.'` ('.$columnList.') VALUES ('.implode(', ', $row).')');
    }

    $count = (int) $mariadb->query('SELECT COUNT(*) FROM `'.$table.'`')->fetchColumn();
    $totalRows += $count;
    $importedTables++;

    fwrite(STDOUT, sprintf(
        'imported:           %-25s %4d rows%s',
        $table,
        $count,
        PHP_EOL,
    ));
}

$mariadb->exec('SET FOREIGN_KEY_CHECKS=1');

fwrite(STDOUT, sprintf(
    "\ndone: %d tables, %d rows.\n",
    $importedTables,
    $totalRows,
));